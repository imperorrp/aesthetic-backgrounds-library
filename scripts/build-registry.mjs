#!/usr/bin/env node
/**
 * Build the registry from the live engine:
 *
 *   registry/index.json          every skin, preset, and layer (built-in + community)
 *   registry/preset.schema.json  JSON Schema for preset manifests, generated from layer schemas
 *
 * Community presets live in registry/community/*.json. Each is validated against the
 * real layer registry; an invalid submission fails the build with its errors.
 *
 *   pnpm registry          write both files
 *   pnpm registry --check  fail if they are stale or a community manifest is invalid (CI)
 *
 * Output is deterministic (no timestamps) so --check can diff it.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';

const check = process.argv.includes('--check');
const root = resolve('.');
const outDir = resolve(root, 'registry');
const communityDir = resolve(outDir, 'community');
mkdirSync(communityDir, { recursive: true });

const server = await createServer({
  root,
  configFile: false,
  logLevel: 'error',
  appType: 'custom',
  server: { middlewareMode: true, hmr: false, ws: false },
  // Only SSR-loads source; no dependency scan over the HTML (the examples import the published package).
  optimizeDeps: { noDiscovery: true, include: [] },
});

let failed = false;
try {
  const lib = await server.ssrLoadModule('/src/lib.ts');
  const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
  const galleryIds = new Set(
    existsSync(resolve(root, 'e2e/__screenshots__/chromium'))
      ? readdirSync(resolve(root, 'e2e/__screenshots__/chromium')).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4))
      : [],
  );

  // Built-ins first, before any community preset is registered.
  const builtins = lib.describeRegistry().map((e) => ({ ...e, preview: galleryIds.has(e.id) ? e.preview : undefined }));
  const builtinIds = new Set(builtins.map((e) => e.id));

  const community = [];
  for (const file of readdirSync(communityDir).filter((f) => f.endsWith('.json')).sort()) {
    const manifest = JSON.parse(readFileSync(resolve(communityDir, file), 'utf8'));
    const result = lib.validatePresetManifest(manifest);
    if (manifest.id && builtinIds.has(manifest.id)) result.errors.push(`id "${manifest.id}" collides with a built-in`);
    if (result.errors.length) {
      failed = true;
      console.error(`✗ community/${file}\n    ${result.errors.join('\n    ')}`);
      continue;
    }
    for (const w of result.warnings) console.warn(`! community/${file}: ${w}`);
    const skin = lib.registerPresetManifest(manifest);
    community.push({
      ...lib.describeSkin(skin),
      source: 'community',
      author: manifest.author,
      preview: galleryIds.has(skin.id) ? `gallery/${skin.id}.png` : undefined,
    });
    console.log(`✓ community/${file}`);
  }

  const index = {
    $comment: 'Generated by scripts/build-registry.mjs. Do not edit by hand.',
    manifestVersion: lib.MANIFEST_VERSION,
    engine: `${pkg.name}@${pkg.version}`,
    entries: [...builtins, ...community],
  };

  // JSON Schema for preset manifests: per-layer `with` options from each layer's schema.
  const layerIds = builtins.filter((e) => e.kind === 'layer').map((e) => e.id);
  const fieldSchema = (f) => {
    const base = { description: f.description ?? f.label };
    switch (f.type) {
      case 'number': return { ...base, type: 'number', minimum: f.min, maximum: f.max, default: f.default };
      case 'boolean': return { ...base, type: 'boolean', default: f.default };
      case 'enum': return { ...base, enum: [...f.values], default: f.default };
      case 'color': return { ...base, type: 'string', default: f.default, examples: ['accent', 'accent2', 'ink', 'inkDim', 'bg', 'hazard', '#ff7a1a'] };
      default: return { ...base, type: 'string', default: f.default };
    }
  };
  const perLayer = builtins
    .filter((e) => e.kind === 'layer')
    .map((e) => ({
      if: { properties: { use: { const: e.id } }, required: ['use'] },
      then: {
        properties: {
          with: {
            type: 'object',
            additionalProperties: false,
            properties: Object.fromEntries(Object.entries(e.schema).map(([k, f]) => [k, fieldSchema(f)])),
          },
        },
      },
    }));
  const schema = {
    $schema: 'http://json-schema.org/draft-07/schema#',
    $id: 'https://unpkg.com/space-background-engine/registry/preset.schema.json',
    title: 'space-background-engine preset manifest',
    $comment: 'Generated by scripts/build-registry.mjs from the layer schemas.',
    type: 'object',
    required: ['id', 'label', 'scene'],
    properties: {
      $schema: { type: 'string' },
      manifestVersion: { type: 'integer', const: lib.MANIFEST_VERSION },
      id: { type: 'string', pattern: '^[a-z][a-z0-9-]{1,48}$' },
      label: { type: 'string', minLength: 1 },
      description: { type: 'string' },
      tags: { type: 'array', items: { type: 'string' } },
      author: { type: 'object', required: ['name'], properties: { name: { type: 'string' }, url: { type: 'string', format: 'uri' } } },
      config: {
        type: 'object',
        properties: {
          palette: {
            oneOf: [
              { type: 'string', description: 'Built-in id (void-cyan, amber, violet) or a hex brand color' },
              {
                type: 'object',
                required: ['from'],
                properties: {
                  from: { type: 'string' },
                  theme: { enum: ['dark', 'light'] },
                  harmony: { enum: lib.HARMONIES },
                },
              },
            ],
          },
          intensity: { type: 'number', minimum: 0, maximum: 1 },
          motion: { enum: ['auto', 'full', 'reduced', 'off'] },
          density: { type: 'number', minimum: 0.25, maximum: 2 },
          light: {
            type: 'object',
            description: 'Scene key light. Omit angle for a seeded upper-corner light.',
            properties: {
              angle: { type: 'number', description: 'Degrees; 0 is right, 270 is straight up' },
              warmth: { type: 'number', minimum: -1, maximum: 1, description: 'Cool (-1) to warm (1) tint of lit areas' },
            },
            additionalProperties: false,
          },
          legibility: {
            oneOf: [
              { enum: ['auto', 'off'] },
              {
                type: 'object',
                properties: {
                  selector: { type: 'string', description: 'Content selector to measure' },
                  strength: { type: 'number', minimum: 0, maximum: 1 },
                },
                additionalProperties: false,
              },
            ],
          },
          quiet: {
            type: 'array',
            description: 'Extra quiet zones as fractions of the viewport',
            items: {
              type: 'object',
              required: ['x', 'y', 'width', 'height'],
              properties: {
                x: { type: 'number', minimum: 0, maximum: 1 },
                y: { type: 'number', minimum: 0, maximum: 1 },
                width: { type: 'number', minimum: 0, maximum: 1 },
                height: { type: 'number', minimum: 0, maximum: 1 },
              },
            },
          },
        },
      },
      scene: {
        type: 'object',
        required: ['layers'],
        properties: {
          layers: {
            type: 'array',
            minItems: 1,
            items: {
              type: 'object',
              required: ['use'],
              properties: {
                use: { enum: layerIds },
                with: { type: 'object' },
                opacity: { type: 'number', minimum: 0, maximum: 1 },
                blend: { enum: ['source-over', 'lighter', 'screen', 'multiply', 'overlay', 'soft-light', 'hard-light', 'color-dodge', 'color-burn', 'darken', 'lighten', 'difference', 'exclusion'] },
                enabled: { type: 'boolean' },
              },
              allOf: perLayer,
            },
          },
        },
      },
    },
  };

  const files = {
    'index.json': JSON.stringify(index, null, 2) + '\n',
    'preset.schema.json': JSON.stringify(schema, null, 2) + '\n',
  };
  for (const [name, content] of Object.entries(files)) {
    const path = resolve(outDir, name);
    if (check) {
      const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
      if (current !== content) {
        failed = true;
        console.error(`✗ registry/${name} is stale. Run \`pnpm registry\` and commit the result.`);
      }
    } else {
      writeFileSync(path, content);
    }
  }
  const counts = index.entries.reduce((acc, e) => ((acc[e.kind] = (acc[e.kind] ?? 0) + 1), acc), {});
  console.log(`${check ? 'checked' : 'wrote'} registry: ${Object.entries(counts).map(([k, n]) => `${n} ${k}s`).join(', ')}, ${community.length} community`);
} finally {
  await server.close();
}
process.exit(failed ? 1 : 0);
